test('侧栏边线悬停显示方向箭头、点击收起恢复、刷新记忆及主工作区扩展', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
  const edge = page.locator('.sidebar-edge-toggle')
  const handle = edge.locator('.sidebar-toggle-handle')
  const sidebar = page.getByRole('complementary', { name: '主导航' })
  await expect(page.locator('.topbar').getByRole('button', { name: '隐藏左侧导航', exact: true })).toHaveCount(0)
  await page.mouse.move(500, 50)
  await expect(handle).toHaveCSS('opacity', '0')
  const sidebarBounds = await sidebar.boundingBox()
  await page.mouse.move(sidebarBounds!.x + sidebarBounds!.width - 1, 350)
  await expect(handle).toHaveCSS('opacity', '1')
  await expect(handle.locator('.lucide-chevron-left')).toHaveCount(1)
  await expect(edge).toHaveAttribute('aria-expanded', 'true')
  const initial = await page.locator('.workspace').boundingBox()
  await page.mouse.click(sidebarBounds!.x + sidebarBounds!.width - 1, 350)
  await expect(sidebar).toBeHidden()
  await expect(page.getByRole('button', { name: '显示左侧导航', exact: true })).toHaveAttribute('aria-expanded', 'false')
  await page.mouse.move(500, 50)
  await expect(handle).toHaveCSS('opacity', '0')
  await page.mouse.move(2, 350)
  await expect(handle).toHaveCSS('opacity', '1')
  await expect(handle.locator('.lucide-chevron-right')).toHaveCount(1)
  const expanded = await page.locator('.workspace').boundingBox()
  expect(expanded!.width - initial!.width).toBeGreaterThan(200)
  expect(expanded!.x).toBe(0)
  await page.getByRole('tab', { name: '连接中心', exact: true }).click()
  await expect(page.getByRole('complementary', { name: '主导航' })).toBeHidden()
  await page.reload()
  await expect(page.getByRole('button', { name: '显示左侧导航', exact: true })).toBeVisible()
  await expect(sidebar).toBeHidden()
  await page.mouse.move(2, 350)
  await expect(handle).toHaveCSS('opacity', '1')
  await page.mouse.click(2, 350)
  await expect(sidebar).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '隐藏左侧导航', exact: true })).toBeVisible()
  await expect(page.getByRole('complementary', { name: '主导航' })).toBeVisible()
})

test('边线收起控件适配侧栏宽度、键盘展开收起，弹窗不被边线覆盖', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  const edge = page.locator('.sidebar-edge-toggle')
  const handle = edge.locator('.sidebar-toggle-handle')
  const sidebar = page.getByRole('complementary', { name: '主导航' })
  for (const width of [1440, 1024, 720]) {
    await page.setViewportSize({ width, height: 900 })
    const bounds = await sidebar.boundingBox()
    const edgeBounds = await edge.boundingBox()
    expect(Math.abs(edgeBounds!.x + edgeBounds!.width / 2 - (bounds!.x + bounds!.width))).toBeLessThanOrEqual(1)
    await page.mouse.move(bounds!.x + bounds!.width - 1, 430)
    await expect(handle).toHaveCSS('opacity', '1')
    await page.mouse.click(bounds!.x + bounds!.width - 1, 430)
    await expect(sidebar).toBeHidden()
    expect((await edge.boundingBox())!.x).toBe(0)
    await page.mouse.move(2, 430)
    await expect(handle.locator('.lucide-chevron-right')).toHaveCount(1)
    await page.mouse.click(2, 430)
    await expect(sidebar).toBeVisible()
  }
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.mouse.move(600, 30)
  await page.keyboard.press('Tab')
  await edge.focus()
  await expect(handle).toHaveCSS('opacity', '1')
  await page.keyboard.press('Enter')
  await expect(sidebar).toBeHidden()
  await expect(edge).toHaveAttribute('aria-expanded', 'false')
  await page.keyboard.press('Space')
  await expect(sidebar).toBeVisible()
  await expect(edge).toHaveAttribute('aria-expanded', 'true')
  await page.getByRole('button', { name: '添加连接', exact: true }).click()
  const layering = await edge.evaluate(element => {
    const bounds = element.getBoundingClientRect()
    const target = document.elementFromPoint(bounds.x + bounds.width / 2, bounds.height / 2)
    return !!target?.closest('.modal-backdrop, dialog')
  })
  expect(layering).toBe(true)
  await page.getByRole('button', { name: '取消', exact: true }).click()
})

test('宽屏滚动选择下方寄存器时详情保持可见，短窗口可独立滚动', async ({ page }) => {
  await page.setViewportSize({ width: 1920, height: 900 })
  await page.goto('/')
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
  await page.getByRole('button', { name: '隐藏左侧导航', exact: true }).click()
  const inspector = page.getByRole('complementary', { name: '寄存器位域详情', exact: true })
  const scratch = page.getByTestId('register-SCRATCH').getByRole('button', { name: 'SCRATCH', exact: true })
  await scratch.click()
  await expect(inspector.getByRole('heading', { name: 'SCRATCH', exact: true })).toBeVisible()
  async function expectWithinWorkspace() {
    await expect.poll(async () => page.evaluate(() => {
      const panel = document.querySelector('.field-inspector')!.getBoundingClientRect()
      const area = document.querySelector('.workspace-content')!.getBoundingClientRect()
      return panel.top >= area.top + 10 && panel.bottom <= area.bottom - 10
    })).toBe(true)
  }
  await expectWithinWorkspace()
  // 改为字段更多的寄存器，缩小高度，确认详情不侵入底部日志。
  await page.getByTestId('register-SYSTEM_CTRL').getByRole('button', { name: 'SYSTEM_CTRL', exact: true }).click()
  await page.setViewportSize({ width: 1920, height: 600 })
  await page.locator('.workspace-content').evaluate(element => { element.scrollTop = 200 })
  await expectWithinWorkspace()
  expect(await inspector.evaluate(element => element.scrollHeight > element.clientHeight)).toBe(true)
  await inspector.evaluate(element => { element.scrollTop = element.scrollHeight })
  await expect(inspector.locator('.inspector-help')).toBeInViewport()
  // 换行重置面板内部位置，但不把左侧表格滚回页面顶部。
  await scratch.click()
  await expect.poll(() => inspector.evaluate(element => element.scrollTop)).toBe(0)
  await expectWithinWorkspace()
  await page.getByRole('button', { name: '关闭底部日志', exact: true }).click()
  await expectWithinWorkspace()
  await page.setViewportSize({ width: 1100, height: 800 })
  await expect(inspector).toHaveCSS('position', 'static')
  await expect(inspector).toHaveCSS('max-height', 'none')
})

