test('主要文字与位编辑器字号及主题对比度', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
  await expect(page.getByTestId('register-SYSTEM_CTRL')).toBeVisible()
  for (const theme of ['light', 'dark']) {
    if (await page.locator('.studio-app').getAttribute('data-theme') !== theme) {
      await page.getByRole('button', { name: '切换明暗主题', exact: true }).click()
    }
    const result = await page.evaluate(() => {
      const root = document.querySelector('.studio-app')!
      const style = getComputedStyle(root)
      const rgb = (value: string) => {
        const probe = document.createElement('span')
        probe.style.color = value
        root.append(probe)
        const channels = getComputedStyle(probe).color.match(/[\d.]+/g)!.map(Number).slice(0, 3)
        probe.remove()
        const linear = channels.map(value => { const unit = value / 255; return unit <= 0.04045 ? unit / 12.92 : ((unit + 0.055) / 1.055) ** 2.4 })
        return linear[0]! * 0.2126 + linear[1]! * 0.7152 + linear[2]! * 0.0722
      }
      const surface = rgb(style.getPropertyValue('--surface'))
      const contrast = (color: string) => { const luminance = rgb(style.getPropertyValue(color)); return (Math.max(luminance, surface) + 0.05) / (Math.min(luminance, surface) + 0.05) }
      return {
        contrast: Object.fromEntries(['--text', '--muted', '--accent', '--teal', '--warning', '--danger'].map(color => [color, contrast(color)])),
        bit: parseFloat(getComputedStyle(document.querySelector('.bit-button')!).fontSize),
        label: parseFloat(getComputedStyle(document.querySelector('.bit-index')!).fontSize),
        log: parseFloat(getComputedStyle(document.querySelector('.log-lines')!).fontSize),
        disabledOpacity: getComputedStyle(document.querySelector('.bit-button:disabled')!).opacity,
      }
    })
    for (const ratio of Object.values(result.contrast)) expect(ratio).toBeGreaterThanOrEqual(4.5)
    expect(result.bit).toBeGreaterThanOrEqual(14)
    expect(result.label).toBeGreaterThanOrEqual(12)
    expect(result.log).toBeGreaterThanOrEqual(13)
    expect(result.disabledOpacity).toBe('1')
  }
})
