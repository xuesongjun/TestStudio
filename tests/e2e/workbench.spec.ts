  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  const state = await page.evaluate(async () => (await fetch('/api/state')).json())
  const dut = state.connections.find((item: { name: string }) => item.name === 'DUT-A')
  if (dut.status === 'connected') await page.getByRole('button', { name: '断开 DUT-A', exact: true }).click()
  await page.getByRole('button', { name: '连接 DUT-A', exact: true }).click()
  await expect(page.getByRole('button', { name: '断开 DUT-A', exact: true })).toBeEnabled()
  const connected = await page.evaluate(async () => (await fetch('/api/state')).json())
  const session = connected.connections.find((item: { name: string }) => item.name === 'DUT-A').session_id
  await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
  await expect(page.getByRole('button', { name: '后台巡检', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: '读取全部', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'SYSTEM_CTRL 待写值' })).toHaveValue('0x00000101')
  await expect(page.getByRole('button', { name: 'SYSTEM_CTRL bit 31', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'DEVICE_STATUS bit 0', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: 'SYSTEM_CTRL bit 0', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'SYSTEM_CTRL 待写值' })).toHaveValue('0x00000100')
  const beforeWrite = await page.evaluate(async id => (await fetch(`/api/connections/${id}/registers/0x1000`)).json(), dut.id)
  expect(beforeWrite.value).toBe(0x101)
  await page.getByRole('button', { name: '写入 SYSTEM_CTRL', exact: true }).click()
  await expect(page.getByTestId('register-SYSTEM_CTRL').getByText('✓ 已校验', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'IRQ_STATUS bit 0', exact: true }).click()
  await page.getByRole('button', { name: '写入 IRQ_STATUS', exact: true }).click()
  await expect(page.getByTestId('register-IRQ_STATUS').locator('.read-value')).toHaveText('0x00000002')
  await page.getByRole('navigation', { name: '管理导航' }).getByRole('button', { name: '任务中心', exact: true }).click()
  await expect(page.getByText('后续采集与测试任务的进度、结果和停止操作会在这里显示。', { exact: true })).toBeVisible()
  await expect(page.getByText('从寄存器工作台启动后台巡检', { exact: false })).toHaveCount(0)
  await page.getByRole('tab', { name: '寄存器工作台', exact: true }).click()
  // 模拟任务只从内部回归入口启动，不再向用户展示巡检按钮。
  expect((await page.request.post('/api/tasks/scan', { data: { connection_id: dut.id, passes: 5 } })).ok()).toBe(true)
