import { expect, test } from '@playwright/test'

test('Excel 导入预览确认、单行/批量删除、导出与刷新持久化', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  const original = await (await page.request.get('/api/registers/definitions')).json()
  try {
    await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
    const template = await (await page.request.get('/api/registers/template')).body()
    await page.getByLabel('寄存器表文件', { exact: true }).setInputFiles({ name: 'registers.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: template })
    const sheets = page.getByRole('dialog', { name: '选择导入工作表', exact: true })
    const selectAll = sheets.getByRole('checkbox', { name: '全选 / 全不选工作表', exact: true })
    await expect(selectAll).toBeChecked()
    await selectAll.uncheck()
    await expect(sheets).toContainText('已选 0 / 1 个可导入工作表')
    await expect(sheets.getByRole('button', { name: '解析选中工作表', exact: true })).toBeDisabled()
    await selectAll.check()
    await expect(sheets).toContainText('已选 1 / 1 个可导入工作表')
    await sheets.getByRole('button', { name: '解析选中工作表', exact: true }).click()
    const preview = page.getByRole('dialog', { name: '导入寄存器表预览', exact: true })
    await expect(preview).toContainText('2 个寄存器')
    await expect(preview).toContainText('EXAMPLE_CTRL')
    await expect(page.getByTestId('register-EXAMPLE_CTRL')).toHaveCount(0)
    await preview.getByRole('button', { name: '确认导入', exact: true }).click()
    await expect(preview).toHaveCount(0)
    await expect(page.getByTestId('register-EXAMPLE_CTRL')).toBeVisible()
    await page.reload()
    await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
    await expect(page.getByTestId('register-EXAMPLE_CTRL')).toBeVisible()
    await page.getByRole('button', { name: '删除 EXAMPLE_STATUS', exact: true }).click()
    const confirmation = page.getByRole('dialog', { name: '删除寄存器配置？', exact: true })
    await expect(confirmation).toContainText('不会清零、复位或写入芯片')
    await confirmation.getByRole('button', { name: '取消', exact: true }).click()
    await expect(page.getByTestId('register-EXAMPLE_STATUS')).toBeVisible()
    await page.getByRole('button', { name: '删除 EXAMPLE_STATUS', exact: true }).click()
    await confirmation.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(page.getByTestId('register-EXAMPLE_STATUS')).toHaveCount(0)
    await page.getByRole('checkbox', { name: '选择 EXAMPLE_CTRL', exact: true }).check()
    await page.getByRole('button', { name: '删除选中 1', exact: true }).click()
    await confirmation.getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(page.getByTestId('register-EXAMPLE_CTRL')).toHaveCount(0)
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: '导出配置', exact: true }).click()
    expect((await download).suggestedFilename()).toBe('teststudio-registers.json')
    await page.reload()
    await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
    await expect(page.getByTestId('register-EXAMPLE_CTRL')).toHaveCount(0)
    await expect(page.getByTestId('register-SYSTEM_CTRL')).toBeVisible()
  } finally {
    const current = await (await page.request.get('/api/registers/definitions')).json()
    await page.request.post('/api/registers/import', { data: { mode: 'replace', expected_revision: current.revision, registers: original.registers } })
  }
})

test('JSON 重复地址不覆盖、全表删除可恢复、非法文件不改变寄存器', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  const original = await (await page.request.get('/api/registers/definitions')).json()
  try {
    await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
    const file = page.getByLabel('寄存器表文件', { exact: true })
    await file.setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('bad json') })
    await expect(page.getByRole('status')).toContainText('JSON 文件编码或格式错误')
    await expect(page.getByTestId('register-SYSTEM_CTRL')).toBeVisible()
    await file.setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
    const preview = page.getByRole('dialog', { name: '导入寄存器表预览', exact: true })
    await expect(preview.getByRole('button', { name: '确认导入', exact: true })).toBeDisabled()
    await expect(preview).toContainText('个地址已存在')
    await preview.getByRole('button', { name: '取消', exact: true }).click()
    await page.getByRole('checkbox', { name: '全选当前筛选寄存器', exact: true }).check()
    await page.getByRole('button', { name: `删除选中 ${original.registers.length}`, exact: true }).click()
    await page.getByRole('dialog', { name: '删除寄存器配置？', exact: true }).getByRole('button', { name: '确认删除', exact: true }).click()
    await expect(page.getByText('寄存器表为空，点击“导入寄存器表”加载 Excel 或 JSON。', { exact: true })).toBeVisible()
    await expect(page.locator('.field-inspector')).toHaveCount(0)
    await file.setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(original)) })
    await preview.getByRole('button', { name: '确认导入', exact: true }).click()
    await expect(page.getByTestId('register-SYSTEM_CTRL')).toBeVisible()
  } finally {
    const current = await (await page.request.get('/api/registers/definitions')).json()
    await page.request.post('/api/registers/import', { data: { mode: 'replace', expected_revision: current.revision, registers: original.registers } })
  }
})

test('日志清空需确认，底部/标签和数据库同步，新日志继续显示', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '清空日志', exact: true }).click()
  const confirmation = page.getByRole('dialog', { name: '清空全部日志？', exact: true })
  await expect(confirmation).toContainText('不仅是当前筛选结果')
  await confirmation.getByRole('button', { name: '取消', exact: true }).click()
  expect((await (await page.request.get('/api/state')).json()).logs.length).toBeGreaterThan(0)
  await page.getByRole('navigation', { name: '管理导航' }).getByRole('button', { name: '日志中心', exact: true }).click()
  await page.getByRole('textbox', { name: '搜索日志', exact: true }).fill('没有匹配的日志')
  await page.getByRole('button', { name: '清空日志', exact: true }).click()
  await confirmation.getByRole('button', { name: '确认清空', exact: true }).click()
  await expect(page.locator('.log-count')).toHaveText('0 条')
  expect((await (await page.request.get('/api/state')).json()).logs).toEqual([])
  await page.reload()
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  await expect(page.locator('.bottom-panel .log-line')).toHaveCount(0)
  const name = `清空后测试-${Date.now()}`
  await page.request.post('/api/connections', { data: { name, kind: 'soc' } })
  await expect(page.locator('.bottom-panel .log-line')).toContainText(`已创建模拟连接配置：${name}`)
  const state = await (await page.request.get('/api/state')).json()
  const connection = state.connections.find((item: { name: string }) => item.name === name)
  await page.request.delete(`/api/connections/${connection.id}`)
})

test('指定实际工作簿选择 BLE_System v1 与 BBPLL v2 后预览并持久化', async ({ page }) => {
  const workbook = process.env.TESTSTUDIO_REGISTER_WORKBOOK
  test.skip(!workbook, '可用 TESTSTUDIO_REGISTER_WORKBOOK 指定只读实际工作簿做额外验证')
  await page.goto('/')
  await expect(page.getByText('内核已连接', { exact: true })).toBeVisible()
  const original = await (await page.request.get('/api/registers/definitions')).json()
  try {
    await page.getByRole('navigation', { name: '功能导航' }).getByRole('button', { name: '寄存器工作台', exact: true }).click()
    await page.getByLabel('寄存器表文件', { exact: true }).setInputFiles(workbook!)
    const sheets = page.getByRole('dialog', { name: '选择导入工作表', exact: true })
    await expect(sheets).toContainText('BLE_System')
    const selectAll = sheets.getByRole('checkbox', { name: '全选 / 全不选工作表', exact: true })
    await selectAll.uncheck()
    await selectAll.check()
    await expect(sheets.getByRole('checkbox', { name: '导入工作表 ADDR', exact: true })).toBeDisabled()
    await expect(sheets.getByRole('checkbox', { name: '导入工作表 ADDR', exact: true })).not.toBeChecked()
    await selectAll.uncheck()
    await sheets.getByRole('checkbox', { name: '导入工作表 BLE_System', exact: true }).check()
    await sheets.getByRole('checkbox', { name: '导入工作表 BBPLL', exact: true }).check()
    await expect(selectAll).toHaveJSProperty('indeterminate', true)
    await sheets.getByRole('button', { name: '解析选中工作表', exact: true }).click()
    const preview = page.getByRole('dialog', { name: '导入寄存器表预览', exact: true })
    await expect(preview).toContainText('32 个寄存器')
    await expect(preview.locator('.import-formats')).toContainText('BLE_System · v1')
    await expect(preview.locator('.import-formats')).toContainText('BBPLL · v2')
    await preview.getByRole('button', { name: '确认导入', exact: true }).click()
    await expect(preview).toHaveCount(0)
    const catalog = await (await page.request.get('/api/registers/definitions')).json()
    expect(catalog.registers.filter((item: { group: string }) => item.group === 'BLE_System')).toHaveLength(30)
    expect(catalog.registers.filter((item: { group: string }) => item.group === 'BBPLL')).toHaveLength(2)
    await page.getByRole('combobox', { name: '选择寄存器表', exact: true }).selectOption('BBPLL')
    await page.locator('.register-name').first().click()
    const details = page.getByRole('complementary', { name: '寄存器位域详情', exact: true })
    await expect(details).not.toContainText('格式 v2')
    await expect(details).not.toContainText('整字初始值')
    await expect(details).not.toContainText('合并 true')
    await expect(details).toContainText('字段初始值')
    await expect(details).not.toContainText('DFT：')
    expect(catalog.registers.some((item: { merged?: unknown; fields: { dft_value?: unknown }[] }) => 'merged' in item || item.fields.some(field => 'dft_value' in field))).toBe(false)
    await page.reload()
    const restored = await (await page.request.get('/api/registers/definitions')).json()
    expect(restored.registers).toEqual(catalog.registers)
  } finally {
    const current = await (await page.request.get('/api/registers/definitions')).json()
    await page.request.post('/api/registers/import', { data: { mode: 'replace', expected_revision: current.revision, registers: original.registers } })
  }
})
